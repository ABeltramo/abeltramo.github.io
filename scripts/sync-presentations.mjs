#!/usr/bin/env node
/**
 * Reads the Marp decks from the presentations repository and writes
 * data/presentations.yaml, which the descent theme shows on the timeline.
 *
 *   node scripts/sync-presentations.mjs [--repo ../presentations] [--dry-run]
 *
 * The date comes from the deck folder when it ends in -YY-MM-DD
 * (for example tech-meeting-26-11-04), then from the `date` key in the
 * deck front matter, then from the last git commit of the file.
 *
 * Descriptions are not in the decks: a description already present in
 * data/presentations.yaml is kept when the url matches.
 */

import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const SITE = resolve(HERE, "..");

const args = process.argv.slice(2);
const repoArg = args.indexOf("--repo");
const REPO = resolve(SITE, repoArg > -1 ? args[repoArg + 1] : process.env.PRESENTATIONS_DIR || "../presentations");
const DRY = args.includes("--dry-run");
const SRC = join(REPO, "src");
const OUT = join(SITE, "data/presentations.yaml");

if (!existsSync(SRC)) {
  console.error(`No presentations source at ${SRC}`);
  console.error("Pass --repo <path> or set PRESENTATIONS_DIR.");
  process.exit(1);
}

function walk(dir) {
  return readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) return walk(full);
    return entry.name === "slides.md" ? [full] : [];
  });
}

function frontMatter(text) {
  const match = /^---\r?\n([\s\S]*?)\r?\n---/.exec(text);
  if (!match) return {};
  const out = {};
  for (const line of match[1].split(/\r?\n/)) {
    const kv = /^([A-Za-z][\w-]*):\s*(.*)$/.exec(line);
    if (!kv) continue;
    let value = kv[2].trim();
    if (/^".*"$/.test(value) || /^'.*'$/.test(value)) value = value.slice(1, -1);
    out[kv[1]] = value;
  }
  return out;
}

function dateFromFolder(dir) {
  const match = /-(\d{2})-(\d{2})-(\d{2})$/.exec(dir);
  return match ? `20${match[1]}-${match[2]}-${match[3]}` : null;
}

function dateFromGit(file) {
  try {
    const out = execFileSync("git", ["log", "-1", "--format=%cs", "--", file], {
      cwd: REPO,
      encoding: "utf8",
      stdio: ["ignore", "pipe", "ignore"]
    }).trim();
    return /^\d{4}-\d{2}-\d{2}$/.test(out) ? out : null;
  } catch {
    return null;
  }
}

function dateFromMtime(file) {
  return statSync(file).mtime.toISOString().slice(0, 10);
}

function previousDescriptions() {
  if (!existsSync(OUT)) return new Map();
  const out = new Map();
  for (const block of readFileSync(OUT, "utf8").split(/^- /m).slice(1)) {
    const url = /^\s*url:\s*(\S+)\s*$/m.exec(block);
    const desc = /^\s*description:\s*"(.*)"\s*$/m.exec(block);
    if (url && desc) out.set(url[1], desc[1]);
  }
  return out;
}

const known = previousDescriptions();
const decks = walk(SRC).map((file) => {
  const text = readFileSync(file, "utf8");
  const meta = frontMatter(text);
  const rel = relative(SRC, dirname(file)).split(/[\\/]/).join("/");
  const folder = rel.split("/").pop();

  const date = dateFromFolder(folder) || meta.date || dateFromGit(file) || dateFromMtime(file);
  const url = `/presentations/${rel}/slides.html`;
  const description = meta.description || known.get(url) || "";

  return { date, title: meta.title || folder, description, url };
});

decks.sort((a, b) => b.date.localeCompare(a.date) || a.title.localeCompare(b.title));

const lines = [
  "# Talks and slides. Generated by scripts/sync-presentations.mjs;",
  "# run it after you add a deck to the presentations repo.",
  "# A description comes from the deck front matter, else from this file.",
  ""
];

for (const deck of decks) {
  lines.push(`- date: ${deck.date}`);
  lines.push(`  title: ${JSON.stringify(deck.title)}`);
  if (deck.description) lines.push(`  description: ${JSON.stringify(deck.description)}`);
  lines.push(`  url: ${deck.url}`);
  lines.push("");
}

const yaml = lines.join("\n").replace(/\n+$/, "\n");

if (DRY) {
  process.stdout.write(yaml);
} else {
  writeFileSync(OUT, yaml);
  console.log(`Wrote ${decks.length} decks to ${relative(SITE, OUT)}`);
}
